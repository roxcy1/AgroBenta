<?php

namespace App\Services\Profile;

use App\Models\User;
use App\Repositories\UserRepository;
use Illuminate\Contracts\Filesystem\Filesystem;
use Illuminate\Database\Eloquent\ModelNotFoundException;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use RuntimeException;
use Throwable;

/**
 * Public avatar storage for the authenticated user.
 *
 * An avatar is served straight from the `public` disk, so its URL is also a
 * capability. A stored `avatar_url` is therefore never trusted as a delete
 * target on its own: replacing an avatar deletes the previous file only when
 * that URL resolves inside the caller's own `avatars/{userId}/` directory. An
 * external URL, a path traversal attempt, or another account's directory is
 * left untouched.
 *
 * The stored filename is always generated by `store()`, never taken from the
 * client, so a caller cannot choose where the new file lands.
 */
class AvatarService
{
    /**
     * The disk that backs `avatar_url`. The `public` disk is linked into the
     * web root by `php artisan storage:link`.
     */
    public const string DISK = 'public';

    public function __construct(
        private readonly UserRepository $users,
    ) {
        //
    }

    /**
     * Store [file] as [user]'s new avatar and remove the previous one.
     *
     * The new file is written first, then persisted, and only then is the old
     * file deleted. A failed write or database update removes the orphaned new
     * file and rethrows, so the account keeps its previous avatar and no
     * unreferenced file is left behind.
     *
     * The previous URL is read from the row under a lock, inside the same
     * transaction as the update. Two overlapping uploads therefore serialize:
     * the second request replaces the first request's URL and deletes the file
     * the first request actually stored, instead of both seeing the same stale
     * URL and leaving one new file orphaned.
     */
    public function upload(User $user, UploadedFile $file): User
    {
        $path = $file->store($this->directory($user), self::DISK);

        // `store()` returns `string|false`. A failed write has nothing to
        // clean up and must not reach the database: there is no URL to persist.
        if ($path === false) {
            throw new RuntimeException('Failed to store the avatar.');
        }

        $previousUrl = null;

        try {
            $updated = DB::transaction(function () use ($user, $path, &$previousUrl): User {
                $locked = $this->users->findForUpdate((int) $user->getKey());

                if ($locked === null) {
                    throw (new ModelNotFoundException)->setModel(
                        User::class,
                        [$user->getKey()],
                    );
                }

                $previousUrl = $locked->avatar_url;

                return $this->users->updateAvatarUrl(
                    $locked,
                    $this->disk()->url($path),
                );
            });
        } catch (Throwable $exception) {
            $this->disk()->delete($path);

            throw $exception;
        }

        $this->deletePrevious($user, $previousUrl);

        return $updated;
    }

    /**
     * Delete the previous avatar only when it is one of [user]'s own files.
     */
    private function deletePrevious(User $user, ?string $previousUrl): void
    {
        $path = $this->ownedPath($user, $previousUrl);

        if ($path !== null) {
            $this->disk()->delete($path);
        }
    }

    /**
     * Resolve [url] to a disk path only when it belongs to [user]'s avatar
     * directory. Anything else returns `null` and is deliberately ignored.
     */
    private function ownedPath(User $user, ?string $url): ?string
    {
        if (! is_string($url) || $url === '') {
            return null;
        }

        $base = $this->disk()->url('');
        if (! str_starts_with($url, $base)) {
            return null;
        }

        $relative = ltrim(substr($url, strlen($base)), '/');

        // Reject traversal before the directory check: `avatars/2/../1/x.jpg`
        // would otherwise resolve into another account's folder. A backslash is
        // rejected too because a Windows filesystem would treat it as a
        // separator even though the URL uses forward slashes.
        $segments = explode('/', $relative);
        if (
            str_contains($relative, '\\')
            || str_ends_with($relative, '/')
            || in_array('..', $segments, true)
            || in_array('.', $segments, true)
        ) {
            return null;
        }

        if (! str_starts_with($relative, $this->directory($user).'/')) {
            return null;
        }

        return $relative;
    }

    private function directory(User $user): string
    {
        return "avatars/{$user->getKey()}";
    }

    private function disk(): Filesystem
    {
        return Storage::disk(self::DISK);
    }
}
